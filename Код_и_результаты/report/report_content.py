def ssr(ds: str, cont: int, strat: str, ci: bool = False) -> str:
    r = SSR.loc[(ds, f"{cont} %", strat)]
    if r.кратность != r.кратность:
        return "около 1"
    s = ("не менее " if r.нижняя_граница else "") + c(r.кратность, 1)
    if ci and not r.нижняя_граница:
        s += f" ({c(r.ди_низ, 1)}–{c(r.ди_верх, 1)})"
    return s


