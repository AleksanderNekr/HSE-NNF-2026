ORDER: list[str] = []


def Rf(*keys: str) -> str:
    nums = []
    for k in keys:
        if k not in ORDER:
            ORDER.append(k)
        nums.append(ORDER.index(k) + 1)
    nums = sorted(set(nums))
    if len(nums) >= 3 and nums == list(range(nums[0], nums[-1] + 1)):
        return f"[{nums[0]}–{nums[-1]}]"
    return "[" + ", ".join(map(str, nums)) + "]"


def PP() -> str:
    return Rf("preprint")


