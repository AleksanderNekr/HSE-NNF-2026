def ks(ds: str, m: str = NNFA, ci: bool = False) -> str:
    v = M[ds]["kstar"][m]
    if v != v:
        return "не достигается"
    s = f"{c(v)}"
    if ci and m in M[ds]["kstar_ci"]:
        lo, hi = M[ds]["kstar_ci"][m]
        s += f" ({c(lo)}–{c(hi)})"
    return s


def f1(ds: str, m: str, k: float) -> str:
    return c(M[ds]["f1"].loc[m, k])


def sig_k(ds: str, rival: str, sign: int) -> list[float]:
    t = M[ds]["tests"]
    sub = t[(t.rival == rival) & (t.p_holm < 0.05) & (sign * t["diff"] > 0)]
    return sorted(sub.k.tolist())


def krange(v: list[float]) -> str:
    if not v:
        return "ни при одной мощности"
    f = lambda x: c(x, 2).rstrip("0").rstrip(",")
    return ("при " + f(v[0]) + "–" + f(v[-1]) if len(v) > 1 else "при " + f(v[0])) + "*σ*_{y}"


def pk(ds: str, mode: str, cont: float, method: str, col: str = "f1") -> float:
    return float(PL[ds]["agg"].loc[(mode, cont, method), col])


def bud(ds: str, mode: str, cont: float) -> float:
    return PL[ds]["budget"][(mode, cont)]


def dn(ds: str, strat: str, col: str = "rmse") -> float:
    return float(D[ds].loc[strat, col])


